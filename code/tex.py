"""LaTeX helpers: coefficient tables (booktabs), number macros, wild-cluster bootstrap, small utilities."""
from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from config import PAPER_TABLES, PROJECT_DIR

NUMBERS_FILE = PROJECT_DIR / "paper" / "numbers.json"


# ------------------------------------------------------------------------------------------
# number macros: python writes numbers.json -> numbers.tex (\newcommand{\nXxx}{...}) so that every
# number quoted in the text is produced by the code (no hand-typed results).
# ------------------------------------------------------------------------------------------
def load_numbers() -> dict:
    if NUMBERS_FILE.exists():
        return json.loads(NUMBERS_FILE.read_text(encoding="utf-8"))
    return {}


def put_number(key: str, value, fmt: str | None = None) -> None:
    nums = load_numbers()
    if fmt is not None:
        if fmt[-1].isdigit():              # '.2' -> '.2f' (avoid scientific notation)
            fmt += "f"
        value = format(value, fmt)
    nums[key] = str(value)
    NUMBERS_FILE.write_text(json.dumps(nums, indent=1, ensure_ascii=False, sort_keys=True), encoding="utf-8")


def write_numbers_tex() -> None:
    nums = load_numbers()
    lines = ["% AUTO-GENERATED by code/tex.py - do not edit by hand"]
    seen: dict = {}
    for k, v in sorted(nums.items()):
        name = "R" + re.sub(r"[^A-Za-z]", "", k)
        if name in seen:
            print(f"WARNING: number-macro collision: {k!r} and {seen[name]!r} -> \{name}")
        seen[name] = k     # LaTeX macro names: letters only, 'R' prefix avoids clashes
        if v.startswith("-"):
            v = "\\ensuremath{-}" + v[1:]            # typographic minus in text and math mode
        v = v.replace("%", "\\%")
        lines.append(f"\\newcommand{{\\{name}}}{{{v}}}")
    (PROJECT_DIR / "paper" / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


# ------------------------------------------------------------------------------------------
def star(p: float) -> str:
    return "\\sym{***}" if p < 0.01 else "\\sym{**}" if p < 0.05 else "\\sym{*}" if p < 0.10 else ""


def fnum(x, d: int = 3) -> str:
    if x is None or (isinstance(x, float) and (np.isnan(x) or np.isinf(x))):
        return "--"
    return f"{x:.{d}f}".replace("-", "$-$")


def fint(x) -> str:
    return f"{int(round(x)):,}".replace(",", "\\,")


def coef_cell(b: float, se: float, p: float, d: int = 3) -> tuple[str, str]:
    return f"{fnum(b, d)}{star(p)}", f"({fnum(se, d)})"


def write_table(name: str, body: str, caption: str, label: str, notes: str, colspec: str,
                header: str, size: str = "\\small", landscape: bool = False) -> Path:
    """Write a self-contained tabular (no float) to paper/tables/<name>.tex.

    The float environment, caption and label live in the manuscript so that they can be edited
    without re-running the code; this file contains only the tabular + notes.
    """
    header = header.rstrip()
    if not header.endswith("\\\\"):
        header += " \\\\"
    # The tabular is shrunk (never enlarged) to the text width; the notes live in a text-width parbox so that
    # they can never run past the margin (threeparttable measures the unscaled width and is not used).
    txt = (f"{size}\n\\setlength{{\\tabcolsep}}{{3.5pt}}\n\\begin{{adjustbox}}{{max width=\\textwidth}}\n"
           f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header}\n\\midrule\n"
           f"{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n"
           f"\\tabnote{{{notes}}}\n")
    p = PAPER_TABLES / f"{name}.tex"
    p.write_text(txt, encoding="utf-8")
    return p


def tex_escape(s: str) -> str:
    return (s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#")
             .replace("$", "\\$"))


# ------------------------------------------------------------------------------------------
# Wild cluster bootstrap-t (Cameron, Gelbach & Miller 2008; Webb weights), one coefficient
# ------------------------------------------------------------------------------------------
def wild_cluster_p(y: np.ndarray, X: np.ndarray, j: int, groups: np.ndarray, B: int = 999,
                   seed: int = 1, null: float = 0.0) -> float:
    """Two-sided wild-cluster-restricted bootstrap-t p-value for H0: beta_j = null.

    y: (n,), X: (n,k) design incl. constant, j: column of the tested coefficient, groups: cluster ids.
    Uses 6-point Webb weights (appropriate with few clusters)."""
    rng = np.random.default_rng(seed)
    g_ids, g = np.unique(groups, return_inverse=True)
    G = len(g_ids)
    n, k = X.shape
    webb = np.array([-np.sqrt(1.5), -1.0, -np.sqrt(0.5), np.sqrt(0.5), 1.0, np.sqrt(1.5)])

    def t_stat(yv: np.ndarray) -> tuple[float, np.ndarray, np.ndarray]:
        XtX_inv = np.linalg.pinv(X.T @ X)
        b = XtX_inv @ (X.T @ yv)
        e = yv - X @ b
        S = np.zeros((G, k))
        np.add.at(S, g, X * e[:, None])
        V = XtX_inv @ (S.T @ S) @ XtX_inv * (G / (G - 1)) * ((n - 1) / (n - k))
        return (b[j] - null) / np.sqrt(V[j, j]), b, e

    t0, _, _ = t_stat(y)
    # restricted model: impose beta_j = null
    Xr = np.delete(X, j, axis=1)
    yr = y - null * X[:, j]
    br = np.linalg.pinv(Xr.T @ Xr) @ (Xr.T @ yr)
    er = yr - Xr @ br
    fitted_r = Xr @ br + null * X[:, j]
    cnt = 0
    for _ in range(B):
        w = rng.choice(webb, size=G)[g]
        ystar = fitted_r + er * w
        tb, _, _ = t_stat(ystar)
        cnt += abs(tb) >= abs(t0)
    return (cnt + 1) / (B + 1)
