def main() -> None:
    df = pd.read_parquet(ANALYSIS_PQ)
    lines = ["# Data dictionary: `data/processed/analysis_contracts.parquet`\n",
             f"{len(df):,} contracts, {df.shape[1]} columns. Generated by `code/11_data_dictionary.py`.\n",
             "| Variable | Type | Non-missing | Description |", "|---|---|---|---|"]
    for c in df.columns:
        lines.append(f"| `{c}` | {df[c].dtype} | {df[c].notna().sum():,} | {DESC.get(c, '')} |")
    (PROJECT_DIR / "docs" / "data_dictionary.md").write_text("\n".join(lines), encoding="utf-8")
    print("data dictionary written")


if __name__ == "__main__":
    main()
